-- ==========================================
-- 1. Product Categories
-- ==========================================

CREATE TABLE product_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    slug VARCHAR(100) NOT NULL UNIQUE,

    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ==========================================
-- 2. Product Category Translations
-- ==========================================

CREATE TABLE product_category_translations (
    category_id BIGINT NOT NULL,

    locale VARCHAR(5) NOT NULL,
    name VARCHAR(255) NOT NULL,

    PRIMARY KEY (category_id, locale),

    CONSTRAINT fk_category_translations_category
        FOREIGN KEY (category_id)
        REFERENCES product_categories(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_category_translation_locale
        CHECK (locale IN ('en', 'vi'))
);


-- ==========================================
-- 3. Products
-- ==========================================

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category_id BIGINT NOT NULL,

    slug VARCHAR(150) NOT NULL UNIQUE,

    image_url VARCHAR(1000),

    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id)
        REFERENCES product_categories(id)
        ON DELETE RESTRICT
);


-- ==========================================
-- 4. Product Translations
-- ==========================================

CREATE TABLE product_translations (
    product_id BIGINT NOT NULL,

    locale VARCHAR(5) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,

    PRIMARY KEY (product_id, locale),

    CONSTRAINT fk_product_translations_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_product_translation_locale
        CHECK (locale IN ('en', 'vi'))
);


-- ==========================================
-- 5. Contact Messages
-- ==========================================

CREATE TABLE contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(255) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    email VARCHAR(320),

    message TEXT NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'NEW',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_contact_messages_status
        CHECK (
            status IN (
                'NEW',
                'IN_PROGRESS',
                'COMPLETED',
                'CANCELLED'
            )
        )
);


-- ==========================================
-- 6. Indexes
-- ==========================================

-- Product queries
CREATE INDEX idx_products_category_id
    ON products(category_id);

CREATE INDEX idx_products_active_sort_order
    ON products(active, sort_order);

-- Category queries
CREATE INDEX idx_product_categories_active_sort_order
    ON product_categories(active, sort_order);

-- Translation queries by locale
CREATE INDEX idx_category_translations_locale
    ON product_category_translations(locale);

CREATE INDEX idx_product_translations_locale
    ON product_translations(locale);

-- Contact message management
CREATE INDEX idx_contact_messages_status
    ON contact_messages(status);

CREATE INDEX idx_contact_messages_created_at
    ON contact_messages(created_at DESC);